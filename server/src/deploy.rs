// Caddyfile and systemd unit generation for Linux hosts.
use crate::config::{preview_origins, BriardrConfig, ConfigError};
use url::Url;

/// Request bodies Briardr accepts at most; Caddy allows the same.
pub const MAX_BODY: &str = "128MB";

/// The Caddy site block(s) for proxy mode: Briardr's origin, then one site per preview slot.
/// `internal_tls`: certificates from Caddy's own local CA instead of Let's Encrypt (test hosts only).
pub fn caddyfile(cfg: &BriardrConfig, internal_tls: bool) -> Result<String, String> {
    let previews = preview_origins(cfg).map_err(config_message)?;
    let public = site_block(
        cfg.public_origin.as_deref().unwrap_or(""),
        u32::from(cfg.port),
        internal_tls,
    )?;
    let mut lines = vec![
        "# Briardr, generated by `briardr caddyfile`. Regenerate it after changing Briardr's configuration."
            .to_string(),
        "# Caddy keeps the public Host header and sets X-Forwarded-For itself (it ignores the client's own),"
            .to_string(),
        "# which is what Briardr's Host/Origin checks and per-client rate limits rely on.".to_string(),
        String::new(),
        public,
    ];
    if previews.is_empty() {
        lines.push("# Previews are off (publicPreviewOrigin is empty).".to_string());
        lines.push(String::new());
    } else {
        lines.push(
            "# Previews: each slot is its own origin, so a dev server's pages can't act as Briardr."
                .to_string(),
        );
        lines.push(String::new());
        for (i, origin) in previews.iter().enumerate() {
            let port = u32::from(cfg.preview_port_start) + i as u32;
            lines.push(site_block(origin, port, internal_tls)?);
        }
    }
    Ok(lines.join("\n"))
}

fn config_message(e: ConfigError) -> String {
    match e {
        ConfigError::Invalid(message) => message,
        other => other.to_string(),
    }
}

/// `new URL(origin).host`: the host name, with the port when it isn't the default one.
fn site_host(origin: &str) -> Result<String, String> {
    let url = Url::parse(origin).map_err(|_| "Invalid URL".to_string())?;
    let host = url.host_str().unwrap_or_default();
    Ok(match url.port() {
        Some(port) => format!("{host}:{port}"),
        None => host.to_string(),
    })
}

fn site_block(origin: &str, port: u32, internal_tls: bool) -> Result<String, String> {
    let site = site_host(origin)?;
    let tls = if internal_tls { "\ttls internal\n" } else { "" };
    Ok(format!(
        "{site} {{\n{tls}\trequest_body {{\n\t\tmax_size {MAX_BODY}\n\t}}\n\treverse_proxy 127.0.0.1:{port} {{\n\t\t# Terminals and live updates are WebSockets; keep them open across `systemctl reload caddy`.\n\t\tstream_close_delay 5m\n\t}}\n}}\n"
    ))
}

pub struct UnitOptions {
    pub user: String,
    pub group: String,
    pub home: String,
    /// The Briardr checkout (working directory).
    pub checkout: String,
    /// Absolute path of the briardr executable (server/target/release/briardr in the checkout).
    pub binary: String,
    /// Absolute path of the herdr executable (not a shim).
    pub herdr: String,
    pub herdr_session: String,
    pub data_dir: String,
    /// PATH for both services: agents in Herdr panes inherit it.
    pub path: String,
    /// Units that provide Briardr's listen addresses, e.g. wg-quick@wg0.service for 10.8.0.1: Briardr starts
    /// after them and pulls them in, but (like Herdr) isn't stopped with them.
    pub network: Vec<String>,
}

/// JSON.stringify for a string.
fn json_string(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_default()
}

/// Paths in WorkingDirectory= can't be quoted; systemd takes the rest of the line as is.
fn plain_path(s: &str) -> Result<&str, String> {
    if s.contains(['\n', '%']) || !s.starts_with('/') {
        return Err(format!(
            "Unsupported path for a systemd unit: {}",
            json_string(s)
        ));
    }
    Ok(s)
}

/// systemd's own quoting: double quotes, with backslashes and quotes escaped; % doubled.
fn quote(s: &str) -> String {
    format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    )
}

/// The same as `^[A-Za-z0-9@_.:-]+\.service$`.
fn is_unit_name(name: &str) -> bool {
    name.strip_suffix(".service").is_some_and(|stem| {
        !stem.is_empty()
            && stem
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '@' | '_' | '.' | ':' | '-'))
    })
}

/// briardr-herdr.service runs the Herdr server (it stays in the foreground; `herdr server stop` ends it
/// cleanly). briardr.service runs Briardr and only *wants* Herdr: restarting or stopping Briardr never
/// touches Herdr or the agents in its panes. Both run as the same non-root user, with that user's HOME,
/// so Briardr finds Herdr's socket under ~/.config/herdr.
/// Returns (unit file name, contents) pairs in a fixed order.
pub fn systemd_units(o: &UnitOptions) -> Result<Vec<(String, String)>, String> {
    let session: Vec<&str> = if o.herdr_session.is_empty() {
        Vec::new()
    } else {
        vec!["--session", o.herdr_session.as_str()]
    };
    let herdr_cmd = |args: &[&str]| -> String {
        std::iter::once(o.herdr.as_str())
            .chain(session.iter().copied())
            .chain(args.iter().copied())
            .map(quote)
            .collect::<Vec<_>>()
            .join(" ")
    };
    for u in &o.network {
        if !is_unit_name(u) {
            return Err(format!("Unsupported unit name: {}", json_string(u)));
        }
    }
    let mut deps = vec!["network-online.target"];
    deps.extend(o.network.iter().map(String::as_str));
    deps.push("briardr-herdr.service");
    let briardr_deps = deps.join(" ");
    let env = [
        format!("Environment={}", quote(&format!("HOME={}", o.home))),
        format!("Environment={}", quote(&format!("PATH={}", o.path))),
        format!("Environment={}", quote("LANG=C.UTF-8")),
    ]
    .join("\n");

    let herdr_unit = format!(
        "# Generated by `briardr systemd-units`. Herdr's server, which owns the terminals and agents.
[Unit]
Description=Herdr server for Briardr ({user})
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User={user}
Group={group}
WorkingDirectory={home}
{env}
ExecStart={exec_start}
ExecStop={exec_stop}
# Stopping Herdr ends every pane, so only restart it after a crash, never on its own.
Restart=on-failure
RestartSec=5
TimeoutStopSec=30

[Install]
WantedBy=multi-user.target
",
        user = o.user,
        group = o.group,
        home = plain_path(&o.home)?,
        env = env,
        exec_start = herdr_cmd(&["server"]),
        exec_stop = herdr_cmd(&["server", "stop"]),
    );

    let briardr_unit = format!(
        "# Generated by `briardr systemd-units`. Briardr itself.
[Unit]
Description=Briardr ({user})
After={briardr_deps}
Wants={briardr_deps}

[Service]
Type=simple
User={user}
Group={group}
WorkingDirectory={checkout}
{env}
Environment={data_dir_env}
ExecStart={exec_start}
Restart=always
RestartSec=3
# Exit code 75: a listen address isn't up yet (e.g. WireGuard); the log says which, and it retries.
# Exit code 78: the configuration is wrong (the log says why). Don't retry until it's fixed.
RestartPreventExitStatus=78
NoNewPrivileges=yes

[Install]
WantedBy=multi-user.target
",
        user = o.user,
        group = o.group,
        briardr_deps = briardr_deps,
        checkout = plain_path(&o.checkout)?,
        env = env,
        data_dir_env = quote(&format!("BRIARDR_DATA_DIR={}", o.data_dir)),
        exec_start = [o.binary.as_str(), "serve"].map(quote).join(" "),
    );

    Ok(vec![
        ("briardr-herdr.service".to_string(), herdr_unit),
        ("briardr.service".to_string(), briardr_unit),
    ])
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::Value;
    use std::fs;
    use std::path::PathBuf;

    fn fixture_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("fixtures/deploy")
    }

    fn load(name: &str) -> Value {
        let path = fixture_dir().join(name);
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
    }

    /// The fixture files whose names start with `prefix`, sorted.
    fn fixtures_with_prefix(prefix: &str) -> Vec<String> {
        let dir = fixture_dir();
        let entries = fs::read_dir(&dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display()));
        let mut names: Vec<String> = entries
            .filter_map(|e| e.ok())
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|n| n.starts_with(prefix) && n.ends_with(".json"))
            .collect();
        names.sort();
        names
    }

    fn config_from(v: &Value) -> BriardrConfig {
        serde_json::from_value(v.clone()).unwrap_or_else(|e| panic!("fixture config: {e}"))
    }

    fn str_field(v: &Value, key: &str) -> String {
        v[key].as_str().unwrap_or_default().to_string()
    }

    fn unit_options(v: &Value) -> UnitOptions {
        UnitOptions {
            user: str_field(v, "user"),
            group: str_field(v, "group"),
            home: str_field(v, "home"),
            checkout: str_field(v, "checkout"),
            binary: str_field(v, "binary"),
            herdr: str_field(v, "herdr"),
            herdr_session: str_field(v, "herdrSession"),
            data_dir: str_field(v, "dataDir"),
            path: str_field(v, "path"),
            network: v["network"]
                .as_array()
                .map(|a| {
                    a.iter()
                        .filter_map(|x| x.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default(),
        }
    }

    fn sample_units() -> UnitOptions {
        UnitOptions {
            user: "briardr".into(),
            group: "briardr".into(),
            home: "/home/briardr".into(),
            checkout: "/opt/briardr".into(),
            binary: "/opt/briardr/server/target/release/briardr".into(),
            herdr: "/usr/local/bin/herdr".into(),
            herdr_session: String::new(),
            data_dir: "/home/briardr/.briardr".into(),
            path: "/usr/local/bin:/usr/bin:/bin".into(),
            network: Vec::new(),
        }
    }

    #[test]
    fn caddyfile_fixtures_match() {
        let names = fixtures_with_prefix("caddyfile.");
        assert!(!names.is_empty());
        for name in names {
            let fx = load(&name);
            let input = fx["input"].as_array().cloned().unwrap_or_default();
            let cfg = config_from(&input[0]);
            let internal_tls = input
                .get(1)
                .and_then(|o| o["internalTls"].as_bool())
                .unwrap_or(false);
            let out = caddyfile(&cfg, internal_tls).unwrap_or_else(|e| panic!("{name}: {e}"));
            assert_eq!(Some(out.as_str()), fx["output"].as_str(), "{name}");
        }
    }

    #[test]
    fn systemd_unit_fixtures_match() {
        let names = fixtures_with_prefix("systemdUnits.");
        assert!(!names.is_empty());
        for name in names {
            let fx = load(&name);
            let input = fx["input"].as_array().cloned().unwrap_or_default();
            let units =
                systemd_units(&unit_options(&input[0])).unwrap_or_else(|e| panic!("{name}: {e}"));
            let expected = fx["output"].as_object().cloned().unwrap_or_default();
            assert_eq!(units.len(), expected.len(), "{name}");
            for (unit, text) in units {
                let want = expected.get(&unit).and_then(Value::as_str);
                assert_eq!(want, Some(text.as_str()), "{name}: {unit}");
            }
        }
    }

    #[test]
    fn every_fixture_is_covered() {
        let dir = fixture_dir();
        let entries = fs::read_dir(&dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display()));
        for entry in entries.filter_map(|e| e.ok()) {
            let name = entry.file_name().to_string_lossy().into_owned();
            assert!(
                name.starts_with("caddyfile.") || name.starts_with("systemdUnits."),
                "no deploy test reads {name}"
            );
        }
    }

    #[test]
    fn caddyfile_rejects_invalid_preview_origin() {
        let mut cfg = config_from(&load("caddyfile.tailscale-defaults.json")["input"][0]);
        cfg.public_preview_origin = Some("http://preview.example.com/{n}".into());
        assert_eq!(
            caddyfile(&cfg, false),
            Err("publicPreviewOrigin must use https.".to_string())
        );
    }

    #[test]
    fn relative_path_is_rejected() {
        let mut o = sample_units();
        o.home = "home/briardr".into();
        assert_eq!(
            systemd_units(&o).err(),
            Some("Unsupported path for a systemd unit: \"home/briardr\"".to_string())
        );
    }

    #[test]
    fn newline_in_path_is_rejected() {
        let mut o = sample_units();
        o.checkout = "/opt/kel\npie".into();
        assert_eq!(
            systemd_units(&o).err(),
            Some("Unsupported path for a systemd unit: \"/opt/kel\\npie\"".to_string())
        );
    }

    #[test]
    fn percent_in_path_is_rejected() {
        let mut o = sample_units();
        o.home = "/home/%u".into();
        assert_eq!(
            systemd_units(&o).err(),
            Some("Unsupported path for a systemd unit: \"/home/%u\"".to_string())
        );
    }

    #[test]
    fn bad_unit_name_is_rejected() {
        let mut o = sample_units();
        o.network = vec!["wg-quick@wg0".into()];
        assert_eq!(
            systemd_units(&o).err(),
            Some("Unsupported unit name: \"wg-quick@wg0\"".to_string())
        );
        o.network = vec!["wg-quick@wg0.service\n".into()];
        assert_eq!(
            systemd_units(&o).err(),
            Some("Unsupported unit name: \"wg-quick@wg0.service\\n\"".to_string())
        );
        o.network = vec![".service".into()];
        assert!(systemd_units(&o).is_err());
    }

    #[test]
    fn systemd_quoting_escapes_backslash_quote_and_percent() {
        assert_eq!(quote(r#"a\b"c%d"#), r#""a\\b\"c%%d""#);
        let mut o = sample_units();
        o.herdr = r#"/opt/a"b\c%d"#.into();
        let units = systemd_units(&o).unwrap_or_else(|e| panic!("{e}"));
        let herdr = &units[0].1;
        assert!(
            herdr.contains(r#"ExecStart="/opt/a\"b\\c%%d" "server""#),
            "{herdr}"
        );
    }
}
